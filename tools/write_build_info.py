#!/usr/bin/env python3
"""Stamp angled/build_info.py with the build id and today's date, and write
the Windows version resource (packaging/version_info.txt)."""
import datetime, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from angled.config import APP_NAME, STUDIO, VERSION  # noqa: E402

today = datetime.date.today()
try:
    sha = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                                  stderr=subprocess.DEVNULL).decode().strip()
except Exception:
    sha = "nogit"
build = "%s.%s" % (today.strftime("%Y%m%d"), sha)
with open(os.path.join(ROOT, "angled", "build_info.py"), "w") as f:
    f.write('"""Generated by tools/write_build_info.py - do not edit."""\n')
    f.write('BUILD = "%s"\nBUILD_DATE = "%s"\n' % (build, today.isoformat()))
v = [int(x) for x in VERSION.split(".")] + [0]
vi = f"""# UTF-8
VSVersionInfo(
  ffi=FixedFileInfo(filevers=({v[0]}, {v[1]}, {v[2]}, 0), prodvers=({v[0]}, {v[1]}, {v[2]}, 0),
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', '{STUDIO}'),
      StringStruct('FileDescription', '{APP_NAME} - angle bubble popping game'),
      StringStruct('FileVersion', 'v{VERSION} (build {build})'),
      StringStruct('InternalName', '{APP_NAME}'),
      StringStruct('LegalCopyright', '(c) 2026 {STUDIO} - Shawn Rapaz and Claude Code - GPLv3'),
      StringStruct('OriginalFilename', '{APP_NAME}-v{VERSION}-win64.exe'),
      StringStruct('ProductName', '{APP_NAME}'),
      StringStruct('ProductVersion', 'v{VERSION}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
with open(os.path.join(ROOT, "packaging", "version_info.txt"), "w") as f:
    f.write(vi)
print("version v%s build %s (%s)" % (VERSION, build, today))
